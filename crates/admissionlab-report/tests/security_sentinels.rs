//! The full-corpus proof for Global Constraint 14 (ROADMAP Task 9.3):
//! **no secret this project knows how to recognize reaches any renderer's
//! output.**
//!
//! `tests/redact.rs` proves each redaction rule fires, one sentinel per
//! rule, on the serialized model. This file is the other half of the
//! claim and the one an operator actually depends on: the model is not
//! what gets pasted into a pull request — a terminal summary, a
//! `result.json`, a `report.html`, and a GitHub step summary are. Every
//! one of them is rendered here from a `LabResult` salted with
//! [`SENTINELS`], and every one of them is searched for every sentinel.
//!
//! # Why "reach" rather than a flat absence assertion
//!
//! Asserting only that a renderer's output lacks the sentinels is
//! satisfiable by a renderer that prints nothing, and two of these four
//! genuinely do print less than the whole document: the terminal summary
//! shows findings rather than every payload, and the GitHub summary
//! truncates each cell at `MAX_CELL_CHARS`. So each renderer is run
//! **twice** — once on the unredacted result to learn which sentinels it
//! can show at all (its *reach*), once on the redacted one to prove every
//! sentinel in that reach is gone. A renderer that stopped rendering
//! payloads would lose its reach and fail
//! [`every_renderer_reaches_some_sentinel_before_redaction`] rather than
//! passing this file vacuously.
//!
//! [`the_json_renderer_reaches_every_sentinel`] pins the strongest case:
//! `result.json` carries the whole document, so its reach must be the
//! complete corpus. That is what makes the corpus itself non-vacuous —
//! every sentinel really is somewhere in the input.
//!
//! # What the corpus covers
//!
//! One unique, greppable string per credential *shape*, not per rule, so
//! a rule that fires on the shape its author had in mind and misses a
//! sibling shape fails here:
//!
//! - bearer tokens, in an `Authorization:` line and in a captured header
//!   map;
//! - `Cookie`, `Set-Cookie`, `Proxy-Authorization`, `X-Api-Key` and
//!   `X-Auth-Token`, in free text and as object keys;
//! - credential-named environment literals in eight naming shapes
//!   (`DB_PASSWORD`, `MYSQL_PASSWD`, `SERVICE_PWD`, `SMTP_PASS`,
//!   `TLS_PASSPHRASE`, `API_TOKEN`, `AWS_SECRET_ACCESS_KEY`,
//!   `REGISTRY_CREDENTIAL`), reached through a final object, a semantic
//!   change payload, and a mutating webhook's JSON Patch;
//! - PEM private keys in four encodings (RSA, EC, PKCS#8, and a block
//!   truncated mid-body), plus **a real private key** generated by
//!   `admissionlab_gateway::generate_test_certificate` — the same call the
//!   Gateway suite makes, so this corpus contains the actual test-CA key
//!   material a run produces rather than a lookalike;
//! - a Secret's `data` and `stringData`, at the top level of a payload
//!   and inside a webhook patch that creates one;
//! - kubeconfig credential material: a `client-key-data:` line, a
//!   `token:` line, and the parsed-object forms of both.
//!
//! Every sentinel is `[a-z0-9-]` only, so no renderer's escaping (HTML
//! entities, Markdown backslashes) can hide one from a substring search
//! by rewriting its characters.
//!
//! # Global Constraint 15
//!
//! [`redaction_preserves_every_finding_and_its_shape`] and
//! [`every_redacted_location_still_shows_that_something_was_there`] are
//! the counterweight: a redaction pass that satisfied this file by
//! deleting the findings would be reporting that two stacks agreed when
//! they did not. Structure, grades, counts, and the *names* of every
//! redacted field survive; only the literals go.


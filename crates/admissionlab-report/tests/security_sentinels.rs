#[test]
fn no_renderer_emits_any_sentinel_after_redaction() {
    let needle = key_needle(test_ca_key_pem());
    let redacted = redact_result(&sentinel_result(), &rules());

    for artifact in render_every_artifact(&redacted, "redacted") {
        let leaked = reached(&artifact, &needle);
        assert!(
            leaked.is_empty(),
            "{} leaked {leaked:?}; rendered output was:\n{}",
            artifact.name,
            artifact.text
        );
    }
}

#[test]
fn the_json_renderer_reaches_every_sentinel() {
    // The corpus's own non-vacuity check, and the strictest form of it:
    // `result.json` carries the whole document, so every sentinel and the
    // generated key must be present *before* redaction. A sentinel this
    // file declares but never plants fails here rather than silently
    // making one absence assertion meaningless.
    let needle = key_needle(test_ca_key_pem());
    let unredacted = sentinel_result();

    let artifacts = render_every_artifact(&unredacted, "unredacted");
    let json = artifacts
        .iter()
        .find(|artifact| artifact.name == "write_json_report")
        .expect("the JSON artifact is always rendered");

    for sentinel in SENTINELS {
        assert!(
            json.text.contains(sentinel),
            "the unredacted corpus is missing {sentinel}; every absence assertion for it would \
             then pass for the wrong reason"
        );
    }
    assert!(
        json.text.contains(&needle),
        "the unredacted corpus is missing the generated private key's body"
    );
}

#[test]
fn every_renderer_reaches_some_sentinel_before_redaction() {
    // The other three renderers show less than the whole document by
    // design (the terminal summarizes, the GitHub summary truncates), so
    // what is pinned here is that each of them reaches *something*: a
    // renderer that stopped showing payloads would satisfy the absence
    // test above for a reason that has nothing to do with redaction.
    let needle = key_needle(test_ca_key_pem());

    for artifact in render_every_artifact(&sentinel_result(), "reach") {
        let reach = reached(&artifact, &needle);
        assert!(
            !reach.is_empty(),
            "{} rendered none of the planted secrets even before redaction, so its absence \
             assertion proves nothing; rendered output was:\n{}",
            artifact.name,
            artifact.text
        );
    }
}

#[test]
fn redaction_preserves_every_finding_and_its_shape() {
    // Global Constraint 15. The whole corpus above is satisfiable by a
    // pass that returned an empty document; this is what forbids it.
    let original = sentinel_result();
    let redacted = redact_result(&original, &rules());

    assert_eq!(redacted.summary, original.summary);
    assert_eq!(
        redacted.summary,
        RunSummary::from_fixtures(&redacted.fixtures),
        "the redacted document's own fixtures must still count to its summary"
    );
    assert_eq!(redacted.policy.disposition, original.policy.disposition);
    assert_eq!(redacted.fixtures.len(), original.fixtures.len());
    assert_eq!(redacted.policy.changes.len(), original.policy.changes.len());
    assert_eq!(redacted.diagnostics.len(), original.diagnostics.len());

    for (after, before) in redacted.fixtures.iter().zip(&original.fixtures) {
        assert_eq!(after.fixture_id, before.fixture_id);
        assert_eq!(after.bucket(), before.bucket());
        assert_eq!(after.changes.len(), before.changes.len());
        for (after, before) in after.changes.iter().zip(&before.changes) {
            assert_eq!(after.severity, before.severity);
            assert_eq!(after.expected, before.expected);
            assert_eq!(after.change.kind, before.change.kind);
            assert_eq!(after.change.object_path, before.change.object_path);
            assert_eq!(after.change.subject, before.change.subject);
            assert_eq!(
                after.change.baseline.is_some(),
                before.change.baseline.is_some(),
                "a payload may be blanked but never dropped: the existence of a difference is \
                 the evidence this tool reports"
            );
            assert_eq!(
                after.change.candidate.is_some(),
                before.change.candidate.is_some()
            );
        }
    }
}

#[test]
fn every_redacted_location_still_shows_that_something_was_there() {
    // Field names, container names, header names and environment variable
    // names all survive. A reader of the redacted document can still see
    // *which* credential moved and *where*, which is the difference
    // between a redacted report and a useless one.
    let redacted = redact_result(&sentinel_result(), &rules());
    let final_object = redacted.fixtures[0]
        .admission
        .as_ref()
        .expect("the critical fixture has an admission comparison")
        .candidate
        .final_object
        .clone()
        .expect("the corpus plants a final object");

    let secret = &final_object["items"][0];
    assert_eq!(secret["metadata"]["name"], json!("app-credentials"));
    assert_eq!(secret["data"], json!({"password": REDACTED}));
    assert_eq!(secret["stringData"], json!({"apiToken": REDACTED}));

    let env = &final_object["items"][1]["spec"]["containers"][0]["env"];
    for (index, name) in [
        "DB_PASSWORD",
        "MYSQL_PASSWD",
        "SERVICE_PWD",
        "SMTP_PASS",
        "TLS_PASSPHRASE",
        "REGISTRY_CREDENTIAL",
    ]
    .into_iter()
    .enumerate()
    {
        assert_eq!(
            env[index],
            json!({"name": name, "value": REDACTED}),
            "the variable's name and its position must survive; only the literal goes"
        );
    }
    assert_eq!(
        env[6],
        json!({
            "name": "DB_HOST",
            "valueFrom": {"secretKeyRef": {"name": "app-credentials", "key": "host"}}
        }),
        "a `valueFrom` reference holds no literal and must be carried verbatim"
    );

    let headers = &final_object["status"]["observedHeaders"];
    assert_eq!(headers["authorization"], json!(REDACTED));
    assert_eq!(headers["content-type"], json!("application/json"));

    let client_config = &final_object["status"]["resolvedClientConfig"];
    assert_eq!(client_config["client-key-data"], json!(REDACTED));
    assert_eq!(client_config["token"], json!(REDACTED));
    assert_eq!(
        client_config["client-certificate-data"],
        json!("LS0tLS1CRUdJTiBDRVJUSUZJQ0FURS0tLS0t"),
        "a certificate is public material a reader may need; only the key half goes"
    );

    // The PEM channel keeps the sentence around the block, and says a
    // private key was there rather than merely dropping it.
    let diagnostic = &redacted.diagnostics[0].message;
    assert!(diagnostic.starts_with("installer output quoted the generated kubeconfig:"));
    assert!(
        diagnostic.contains(&format!("client-key-data: {REDACTED}")),
        "the field name stays, the value goes: {diagnostic}"
    );
    assert!(diagnostic.ends_with("which it should not have"));

    let expected_diagnostic = &redacted.fixtures[1]
        .admission
        .as_ref()
        .expect("the expected fixture has an admission comparison")
        .baseline
        .diagnostics[0]
        .message;
    assert_eq!(
        expected_diagnostic.matches(REDACTED_PRIVATE_KEY).count(),
        2,
        "both the complete PKCS#8 block and the truncated one must be replaced, and the \
         replacement must say a private key was there: {expected_diagnostic}"
    );

    // A live response header keeps its name, so a header present on one
    // side and absent on the other is still a visible difference.
    let probe = &redacted.fixtures[4]
        .gateway
        .as_ref()
        .expect("the gateway fixture carries a comparison")
        .candidate
        .probes[0];
    assert_eq!(probe.response_headers["set-cookie"], REDACTED);
    assert_eq!(probe.response_headers["x-auth-token"], REDACTED);
    assert_eq!(probe.status, 503, "an observed status is not a secret");
}

#[test]
fn the_corpus_is_redacted_idempotently_and_without_mutating_its_input() {
    let original = sentinel_result();
    let snapshot = original.clone();

    let once = redact_result(&original, &rules());
    let twice = redact_result(&once, &rules());

    assert_eq!(
        original, snapshot,
        "redact_result must leave its argument untouched"
    );
    assert_eq!(
        once, twice,
        "redacting an already-redacted result must be a no-op, because nothing in the pipeline \
         tracks whether a given result has been through the pass"
    );
}


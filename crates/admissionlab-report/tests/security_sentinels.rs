/// One rendered artifact: the name a failure should name, and its bytes.
struct Rendered {
    name: &'static str,
    text: String,
}

/// A temporary directory that removes itself when dropped.
///
/// A test holds one for as long as it uses paths underneath it. `Drop`
/// runs on a panicking assertion too, which an explicit delete at the
/// end of a test does not — that is what keeps a `cargo test` run from
/// leaving a directory per test behind in the system temp directory.
struct TempDir(PathBuf);

impl TempDir {
    /// The directory's path, valid for as long as this guard lives.
    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// A fresh, guaranteed-unique directory under the system temp directory,
/// following the same convention as this crate's other filesystem tests.
fn unique_temp_dir(label: &str) -> TempDir {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "admissionlab-report-sentinel-test-{}-{label}-{n}",
        std::process::id()
    ));
    std::fs::create_dir_all(&dir).expect("create unique temp dir");
    TempDir(dir)
}

/// Every artifact a run produces, rendered from `result`.
///
/// The two file-writing renderers are exercised through their *writing*
/// entry points and read back from disk, not through an in-memory
/// shortcut: what an operator attaches to an issue is the file, and a
/// writer that serialized something other than what it rendered would
/// pass an in-memory check.
fn render_every_artifact(result: &LabResult, label: &str) -> Vec<Rendered> {
    let dir = unique_temp_dir(label);

    let json_path = dir.path().join("result.json");
    write_json_report(&json_path, result).expect("the JSON report writes");
    let json_text = std::fs::read_to_string(&json_path).expect("the JSON report reads back");

    let html_path = dir.path().join("report.html");
    write_html_report(&html_path, result).expect("the HTML report writes");
    let html_text = std::fs::read_to_string(&html_path).expect("the HTML report reads back");

    // Self-cleaning: `dir` removes itself when this function returns, and
    // the assertions below run on the text, not the files.

    vec![
        Rendered {
            name: "redact_result -> serde_json",
            text: serde_json::to_string(result).expect("a LabResult always serializes"),
        },
        Rendered {
            name: "write_json_report",
            text: json_text,
        },
        Rendered {
            name: "render_terminal",
            text: render_terminal(result, &TerminalOptions::for_stream(false, true)),
        },
        Rendered {
            name: "write_html_report",
            text: html_text,
        },
        Rendered {
            name: "render_github_summary",
            text: render_github_summary(result),
        },
    ]
}

/// The sentinels `artifact` actually contains — a renderer's *reach*.
fn reached(artifact: &Rendered, key_needle: &str) -> Vec<String> {
    SENTINELS
        .iter()
        .map(|sentinel| (*sentinel).to_owned())
        .chain(std::iter::once(key_needle.to_owned()))
        .filter(|needle| artifact.text.contains(needle.as_str()))
        .collect()
}


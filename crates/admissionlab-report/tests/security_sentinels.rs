/// A real PEM private key, generated exactly the way a Gateway TLS suite
/// generates the one it installs into the disposable cluster.
///
/// Using the real call rather than a hand-written lookalike is the point:
/// if `admissionlab_gateway`'s key encoding ever changed to a label this
/// project's PEM rule does not recognize, a lookalike would keep passing
/// and this does not.
/// Generated **once per test binary** and shared: every call mints a
/// fresh key, so a test that generated one key for the corpus and another
/// for the needle would be searching for a string that was never planted
/// — which is a test that can only pass.
fn test_ca_key_pem() -> &'static str {
    static KEY: OnceLock<String> = OnceLock::new();
    KEY.get_or_init(|| {
        let certificate =
            admissionlab_gateway::generate_test_certificate("sentinel.admissionlab.test")
                .expect("a host under the test TLD always yields a certificate");
        String::from_utf8(certificate.expose_key_pem().to_vec())
            .expect("a generated PEM key is valid UTF-8")
    })
}

/// The longest all-alphanumeric run inside `key_pem`'s base64 body, used
/// as the needle for the generated key.
///
/// Alphanumeric-only so that no renderer's escaping can rewrite it: a
/// base64 body can contain `+` and `/`, neither of which any of these
/// four renderers escapes today, but a needle that depends on that is a
/// needle that can fail for a reason unrelated to redaction.
fn key_needle(key_pem: &str) -> String {
    let needle = key_pem
        .lines()
        .filter(|line| !line.starts_with("-----"))
        .flat_map(|line| line.split(|c: char| !c.is_ascii_alphanumeric()))
        .max_by_key(|run| run.len())
        .unwrap_or_default()
        .to_owned();
    assert!(
        needle.len() >= 16,
        "a generated key's base64 body must contain a long alphanumeric run to search for; \
         got {needle:?}"
    );
    needle
}


/// [`canonical_result`] salted with every string in [`SENTINELS`] plus a
/// real generated private key.
///
/// Placement is by *channel*, not by convenience: each sentinel sits in a
/// field a real run genuinely fills from something outside this project's
/// control — an API-server warning, a webhook's rejection message, a
/// mutating webhook's patch, a controller's condition reason, a live HTTP
/// response header, a user-written expectation reason, a captured final
/// object. A redaction pass that walked only the obvious channel (the
/// final object) fails on most of this corpus.
fn sentinel_result() -> LabResult {
    let mut result = canonical_result();

    salt_admission_fixtures(&mut result);
    salt_gateway_probe(&mut result);
    salt_run_level_channels(&mut result);

    // The policy section carries the same changes the fixtures do, so it
    // is rebuilt from them: a pass that walked `fixtures` and stopped
    // would otherwise leave the run-wide list unredacted.
    result.policy.changes = result
        .fixtures
        .iter()
        .flat_map(|fixture| fixture.changes.iter().cloned())
        .collect();

    result
}

/// The three admission fixtures: a captured final object, an API-server
/// warning, a mutating webhook's patch, a change payload, a divergence
/// explanation, a webhook diagnostic, and a rejection message.
fn salt_admission_fixtures(result: &mut LabResult) {
    // --- fixture 0: the critical admission comparison ---------------
    let critical = &mut result.fixtures[0];
    let admission = critical
        .admission
        .as_mut()
        .expect("the critical fixture always has an admission comparison");

    admission.candidate.final_object = Some(sentinel_final_object());
    admission.candidate.warnings.push(format!(
        "upstream replied 401; the request line was\nAuthorization: Bearer \
         {AUTHORIZATION_TEXT}\nand the proxy hop added\nProxy-Authorization: Basic \
         {PROXY_AUTHORIZATION_TEXT}\nbefore retrying"
    ));
    admission
        .candidate
        .warnings
        .push(format!("X-Api-Key: {API_KEY_TEXT}"));
    admission.candidate.trace.invocations[0].patch = Some(vec![
        json_patch::PatchOperation::Add(json_patch::AddOperation {
            path: "/spec/template/spec/containers/1/env/0"
                .parse()
                .expect("a literal RFC 6901 pointer parses"),
            value: json!({"name": "API_TOKEN", "value": ENV_TOKEN}),
        }),
        json_patch::PatchOperation::Add(json_patch::AddOperation {
            path: "/items/-"
                .parse()
                .expect("a literal RFC 6901 pointer parses"),
            value: json!({
                "apiVersion": "v1",
                "kind": "Secret",
                "metadata": {"name": "injected-registry-pull"},
                "data": {".dockerconfigjson": SECRET_IN_PATCH}
            }),
        }),
    ]);

    let change = &mut critical.changes[0].change;
    change.baseline = Some(json!({"name": "AWS_SECRET_ACCESS_KEY", "value": "previous-value"}));
    change.candidate = Some(json!({
        "name": "AWS_SECRET_ACCESS_KEY",
        "value": ENV_SECRET_ACCESS_KEY
    }));
    if let Some(origin) = change.origin.as_mut() {
        origin.explanation =
            format!("the candidate patch set it after replaying\nX-Api-Key: {API_KEY_MAP}");
    }

    // --- fixture 1: PEM material in a change payload -----------------
    let expected = &mut result.fixtures[1];
    expected.changes[0].change.baseline = Some(json!(format!(
        "-----BEGIN EC PRIVATE KEY-----\n{PEM_EC}\n-----END EC PRIVATE KEY-----"
    )));
    let expected_admission = expected
        .admission
        .as_mut()
        .expect("the expected fixture always has an admission comparison");
    expected_admission.baseline.diagnostics[0].message = format!(
        "the webhook's own bootstrap wrote\n-----BEGIN PRIVATE KEY-----\n{PEM_PKCS8}\n-----END \
         PRIVATE KEY-----\nand the log was clipped at\n-----BEGIN OPENSSH PRIVATE KEY-----\n\
         {PEM_TRUNCATED}"
    );
    if let Some(divergence) = expected_admission.first_divergence.as_mut() {
        divergence.explanation = format!(
            "the two traces are identical; the candidate's own client config held\n\
             client-key-data: {KUBECONFIG_CLIENT_KEY_TEXT}\ntoken: {KUBECONFIG_TOKEN_TEXT}"
        );
    }

    // --- fixture 3: a webhook's rejection message --------------------
    let identical_admission = result.fixtures[3]
        .admission
        .as_mut()
        .expect("the identical fixture always has an admission comparison");
    for side in [
        &mut identical_admission.baseline,
        &mut identical_admission.candidate,
    ] {
        side.decision = admissionlab_admission::AdmissionDecision::Rejected {
            code: Some(403),
            message: format!(
                "denied: the pod's imagePullSecret resolved to\npassword: \
                 {KUBECONFIG_PASSWORD_FIELD}"
            ),
        };
    }
}

/// A live data plane's response headers — the one channel in the document
/// that carries headers a *server this project did not write* chose to
/// send.
fn salt_gateway_probe(result: &mut LabResult) {
    let gateway = result.fixtures[4]
        .gateway
        .as_mut()
        .expect("the gateway fixture always carries a comparison");
    let probe = gateway
        .candidate
        .probes
        .first_mut()
        .expect("the gateway case always answers at least one probe");
    probe
        .response_headers
        .insert("set-cookie".to_owned(), format!("session={SET_COOKIE_KEY}"));
    probe
        .response_headers
        .insert("x-auth-token".to_owned(), AUTH_TOKEN_KEY.to_owned());
}

/// The channels that hang off the run rather than off a fixture: a
/// diagnostic and its public context, a stale expectation's reason, and a
/// user-written migration expectation.
fn salt_run_level_channels(result: &mut LabResult) {
    result.diagnostics[0].message = format!(
        "installer output quoted the generated kubeconfig:\n    client-key-data: \
         {KUBECONFIG_CLIENT_KEY_TEXT}\n    token: {KUBECONFIG_TOKEN_TEXT}\nwhich it should not \
         have"
    );
    result.diagnostics[0].context.insert(
        "warning".to_owned(),
        RedactedValue::Public(format!(
            "-----BEGIN RSA PRIVATE KEY-----\n{PEM_RSA}\n-----END RSA PRIVATE KEY-----"
        )),
    );
    result.policy.stale_expectations[0].reason = format!(
        "no matching change was observed; the recorded session was\nCookie: sid={COOKIE_TEXT}"
    );

    // The real thing, from the same call the Gateway suite makes: a
    // private key this project generates for itself, in a user-written
    // field that reaches every renderer.
    result.migration.as_mut().expect("a migration case")[0].unmatched_expectations[0].reason = format!(
        "kept until the rollout is confirmed; the retired listener key was\n{}",
        test_ca_key_pem()
    );
}

